#!/usr/bin/env node
/**
 * Build the browser artifact `client.js` from `src/*.js`.
 *
 * The browser module loader executes `window.__ModuleLoader__.load({id,
 * factory})`; the factory concatenates the plain-script sources into one
 * function scope and returns `{ inject, apply }`. Locale dictionaries are
 * embedded from `locale/*.json` (single source of truth: the JSON files, whose
 * `meta` block also feeds Plugin Manager).
 *
 * Usage: node build.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const PACKAGE_NAME = 'dsh-response-annotations';
const SOURCE_FILES = [
  'core.js',
  'store.js',
  'selection.js',
  'ui.js',
  'capsule.js',
  'usertext.js',
  'apply.js',
];
const LOCALE_FILES = ['en', 'zh'];

function readText(relativePath) {
  return readFileSync(join(ROOT, relativePath), 'utf8');
}

function loadLocale(name) {
  const raw = readText(join('locale', name + '.json'));
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new Error(`locale/${name}.json is not valid JSON: ${error.message}`);
  }
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error(`locale/${name}.json must be a JSON object`);
  }
  const { meta, ...messages } = parsed;
  if (meta === undefined || typeof meta !== 'object' || Array.isArray(meta)) {
    throw new Error(`locale/${name}.json is missing its meta object`);
  }
  for (const key of ['title', 'description']) {
    if (typeof meta[key] !== 'string' || meta[key].length === 0) {
      throw new Error(`locale/${name}.json meta.${key} must be a non-empty string`);
    }
  }
  return messages;
}

function checkLocaleParity(dictionaries) {
  const [first, ...rest] = LOCALE_FILES;
  const expected = Object.keys(dictionaries[first]).sort();
  for (const name of rest) {
    const actual = Object.keys(dictionaries[name]).sort();
    const missing = expected.filter((key) => !actual.includes(key));
    const extra = actual.filter((key) => !expected.includes(key));
    if (missing.length > 0 || extra.length > 0) {
      throw new Error(
        `locale/${name}.json key mismatch (missing: ${missing.join(', ') || '-'}; extra: ${extra.join(', ') || '-'})`,
      );
    }
  }
}

function loadSources() {
  const chunks = [];
  for (const file of SOURCE_FILES) {
    const source = readText(join('src', file));
    if (/^\s*(?:import|export)\s/m.test(source)) {
      throw new Error(`src/${file} must be a plain script (no import/export)`);
    }
    if (/__ModuleLoader__/.test(source)) {
      throw new Error(`src/${file} must not reference the module loader directly`);
    }
    chunks.push(`// ---- src/${file} ----\n${source.trimEnd()}\n`);
  }
  return chunks.join('\n');
}

function build() {
  const dictionaries = {};
  for (const name of LOCALE_FILES) dictionaries[name] = loadLocale(name);
  checkLocaleParity(dictionaries);

  const header = [
    '/*',
    ` * ${PACKAGE_NAME} - generated by build.mjs; do not edit directly.`,
    ' * Source files: src/core.js, src/store.js, src/selection.js, src/ui.js,',
    ' * src/capsule.js, src/usertext.js, src/apply.js (+ locale/*.json).',
    ' */',
    'window.__ModuleLoader__.load({',
    `  id: '${PACKAGE_NAME}',`,
    '  factory(require) {',
    "    const React = require('react');",
    '    const h = React.createElement;',
    '',
    `    const LOCALE_EN = ${JSON.stringify(dictionaries.en)};`,
    `    const LOCALE_ZH = ${JSON.stringify(dictionaries.zh)};`,
    '',
  ].join('\n');

  const footer = [
    '',
    '    return { inject, apply };',
    '  },',
    '});',
    '',
  ].join('\n');

  const output = header + '\n' + loadSources() + footer;
  writeFileSync(join(ROOT, 'client.js'), output, 'utf8');

  const bytes = Buffer.byteLength(output, 'utf8');
  const lines = output.split('\n').length;
  process.stdout.write(
    `built client.js (${bytes} bytes, ${lines} lines) from ${SOURCE_FILES.length} sources and ${LOCALE_FILES.length} locales\n`,
  );
}

build();
